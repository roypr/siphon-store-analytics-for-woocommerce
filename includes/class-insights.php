<?php
/**
 * Insights Engine
 *
 * Orchestrates the full insight pipeline:
 * 1. Calls AI to generate structured JSON (SQL + type + config)
 * 2. Parses the JSON response with fallback chain
 * 3. Executes the SQL via the validator + wpdb
 * 4. Classifies results and renders via the Insight Renderer
 *
 * @package SILC_WooInsight_AI
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

require_once SILC_WIA_PATH . 'includes/class-ai-service.php';
require_once SILC_WIA_PATH . 'includes/class-api.php';
require_once SILC_WIA_PATH . 'includes/class-insight-renderer.php';
require_once SILC_WIA_PATH . 'includes/class-sql-validator.php';
require_once SILC_WIA_PATH . 'includes/class-woo-schema.php';

/**
 * Insights class.
 */
class SILC_WIA_Insights {

	/**
	 * Default cache TTL in seconds (1 hour).
	 * Overridden by the 'cache_ttl' setting if configured.
	 */
	const CACHE_TTL = 3600;

	/**
	 * Generate an insight from a natural language question.
	 *
	 * Full pipeline: AI → Parse JSON → Validate → Execute → Render.
	 *
	 * @param string $question The user's question.
	 * @return array The complete insight response.
	 */
	public static function generate_insight( string $question ): array {
		// Cache the rendered answer for the configured TTL. The key includes the
		// active AI backend (and, for BYOK, the endpoint and model), so switching
		// backend, provider or model cannot serve a result that was generated by
		// the previous configuration.
		$cache_key = 'silc_wia_insight_' . md5( SILC_WIA_AI_Service::get_cache_signature() . '|' . $question );
		$cached    = get_transient( $cache_key );
		if ( false !== $cached ) {
			return $cached;
		}

		// Get schema context.
		$schema_context = SILC_WIA_Woo_Schema::get_schema_context();

		// Step 1: Call AI to generate structured insight JSON. The service
		// dispatches to the WordPress AI Client or the plugin's own client,
		// depending on the site and the Backend setting.
		$ai_result = SILC_WIA_AI_Service::generate_insight( $question, $schema_context );

		if ( ! $ai_result['success'] ) {
			$response = array(
				'success' => false,
				'error'   => $ai_result['error'],
				'type'    => 'error',
			);
			return $response;
		}

		$insight_data = $ai_result['insight'];

		// Check if AI returned an error_code (forbidden / out-of-scope).
		if ( ! empty( $insight_data['error_code'] ) ) {
			$response = array(
				'success'    => false,
				'error_code' => $insight_data['error_code'],
				'error'      => $insight_data['error_message'] ?? self::get_error_message( $insight_data['error_code'] ),
				'type'       => 'error',
			);
			return $response;
		}

		$sql          = $insight_data['sql'] ?? '';
		$type         = $insight_data['type'] ?? 'answer';

		// Step 2: Validate SQL.
		$validation = SILC_WIA_SQL_Validator::validate( $sql );
		if ( ! $validation['valid'] ) {
			$response = array(
				'success' => false,
				'error'   => $validation['error'],
				'type'    => 'error',
				'error_code' => 'SQL_VALIDATION',
				'sql'     => $sql,
			);
			return $response;
		}

		// Step 3: Execute SQL.
		$execution = SILC_WIA_SQL_Validator::execute( $validation['sql'] );

		if ( ! $execution['success'] ) {
			$response = array(
				'success' => false,
				'error'   => self::format_query_error( $execution['error'] ),
				'type' => 'error',
				'error_code' => 'QUERY_ERROR',
				'sql'  => $validation['sql'],
			);
			return $response;
		}

		$data       = $execution['data'] ?? array();
		$columns    = ! empty( $data ) ? array_keys( $data[0] ) : array();
		$sql_time   = $execution['time_ms'] ?? 0;
		$rows_count = $execution['rows'] ?? count( $data );

		// Step 4: If AI type is invalid or data is empty, use fallback classification.
		if ( empty( $data ) ) {
			$response = self::build_empty_response( $question, $validation['sql'], $type, $sql_time );
			return $response;
		}

		if ( ! in_array( $type, array( 'chart', 'list', 'answer' ), true ) ) {
			$fallback    = self::classify_result( $data, $columns );
			$type        = $fallback['type'];
			$insight_data = array_merge( $insight_data, $fallback['config'] );
		}

		// Step 5: Render based on type.
		$response = self::render_by_type( $data, $insight_data, $type, $question );

		$response['sql']        = $validation['sql'];
		$response['sql_time_ms'] = $sql_time;
		$response['rows_returned'] = $rows_count;
		$response['columns']    = $columns;
		$response['question']   = $question;

		// Presentation config as it came from the AI, before rendering filled it
		// with result data. History stores this (never the rows) so an entry can
		// be replayed by re-executing the SQL.
		$response['render_config'] = array(
			'type'         => $type,
			'title'        => $insight_data['title'] ?? '',
			'chart_config' => $insight_data['chart_config'] ?? null,
			'list_config'  => $insight_data['list_config'] ?? null,
			'answer_text'  => $insight_data['answer_text'] ?? null,
		);

		// Cache the result using the configured TTL (falls back to CACHE_TTL constant).
		$cache_ttl = SILC_WIA_API::get_cache_ttl();
		if ( $cache_ttl > 0 ) {
			set_transient( $cache_key, $response, $cache_ttl );
		}

		return $response;
	}

	/**
	 * Get a user-friendly error message for a given error code.
	 *
	 * @param string $error_code The error code.
	 * @return string
	 */
	public static function get_error_message( string $error_code ): string {
		switch ( $error_code ) {
			case 'FORBIDDEN':
				return __( 'This action is not allowed. I can only answer questions about your store data — I cannot modify or delete anything.', 'siphon-store-analytics-for-woocommerce' );
			case 'OUT_OF_SCOPE':
				return __( 'I can only help with WooCommerce store questions. Try asking about sales, products, orders, or customers.', 'siphon-store-analytics-for-woocommerce' );
			case 'NOT_WOOCOMMERCE':
				return __( 'I only work with WooCommerce store data. That request involves non-store content I cannot access.', 'siphon-store-analytics-for-woocommerce' );
			default:
				return __( 'Unable to process this request.', 'siphon-store-analytics-for-woocommerce' );
		}
	}

	/**
	 * Format a database execution error for the dashboard.
	 *
	 * A missing Analytics lookup table is a data-prerequisite issue, not a bad
	 * query, so it gets an actionable message instead of the raw MySQL error.
	 *
	 * @param string $error Raw database error.
	 * @return string
	 */
	private static function format_query_error( string $error ): string {
		if ( SILC_WIA_Woo_Schema::is_analytics_error( $error ) ) {
			return SILC_WIA_Woo_Schema::get_analytics_unavailable_message();
		}

		return sprintf(
			/* translators: %s: database error */
			__( 'Query error: %s', 'siphon-store-analytics-for-woocommerce' ),
			$error
		);
	}

	/**
	 * Build a response for empty results.
	 *
	 * @param string $question The original question.
	 * @param string $sql      The SQL executed.
	 * @param string $type     The intended output type.
	 * @param float  $sql_time Query execution time.
	 * @return array
	 */
	private static function build_empty_response( string $question, string $sql, string $type, float $sql_time ): array {
		$empty_message = __( 'No results found.', 'siphon-store-analytics-for-woocommerce' );

		if ( preg_match( '/last\s+(week|month|year|7\s*days|30\s*days)/i', $question ) ) {
			$empty_message = __( 'No data found for the specified period.', 'siphon-store-analytics-for-woocommerce' );
		} elseif ( preg_match( '/pending|cancelled|refunded|failed/i', $question ) ) {
			$empty_message = __( 'No orders found with that status.', 'siphon-store-analytics-for-woocommerce' );
		}

		return array(
			'success'      => true,
			'type'         => $type,
			'sql'          => $sql,
			'sql_time_ms'  => $sql_time,
			'rows_returned' => 0,
			'empty'        => true,
			'empty_message' => $empty_message,
			'question'     => $question,
			'columns'      => array(),
			'render_config' => array(
				'type'  => $type,
				'title' => '',
			),
		);
	}

	/**
	 * Render insight data by type using the appropriate renderer method.
	 *
	 * @param array  $data         Raw result rows.
	 * @param array  $insight_data The parsed AI insight data.
	 * @param string $type         The output type (chart, list, answer).
	 * @param string $question     The original question.
	 * @return array
	 */
	private static function render_by_type( array $data, array $insight_data, string $type, string $question ): array {
		// The insight config comes from the AI response or from a stored result
		// posted by the dashboard, so a key can hold any JSON type. The
		// renderers take typed arrays, so narrow before handing it over.
		$response = array(
			'success' => true,
			'type'    => $type,
			'title'   => is_scalar( $insight_data['title'] ?? null ) ? (string) $insight_data['title'] : '',
		);

		switch ( $type ) {
			case 'chart':
				$chart_config             = is_array( $insight_data['chart_config'] ?? null ) ? $insight_data['chart_config'] : array();
				$response['chart_config'] = SILC_WIA_Insight_Renderer::prepare_chart_data( $data, $chart_config );
				$response['list_data']    = null;
				$response['answer_text']  = null;
				break;

			case 'list':
				$list_config = is_array( $insight_data['list_config'] ?? null ) ? $insight_data['list_config'] : array();
				$link_map    = is_array( $list_config['link_columns'] ?? null ) ? $list_config['link_columns'] : array();

				$response['list_data']   = SILC_WIA_Insight_Renderer::prepare_list_data( $data, $link_map );
				$response['list_config'] = array(
					'title_column'    => is_scalar( $list_config['title_column'] ?? null )
						? (string) $list_config['title_column']
						: ( ! empty( $data[0] ) ? array_keys( $data[0] )[0] : '' ),
					'display_columns' => is_array( $list_config['display_columns'] ?? null )
						? $list_config['display_columns']
						: ( ! empty( $data[0] ) ? array_keys( $data[0] ) : array() ),
				);
				$response['chart_config'] = null;
				$response['answer_text']  = null;
				break;

			case 'answer':
			default:
				$answer_text             = is_scalar( $insight_data['answer_text'] ?? null ) ? (string) $insight_data['answer_text'] : '';
				$answer_data             = SILC_WIA_Insight_Renderer::prepare_answer_data( $data, $question );
				$response['answer_text'] = $answer_text ?: $answer_data['formatted'];
				$response['answer_value'] = $answer_data['value'];
				$response['answer_label'] = $answer_data['label'];
				$response['chart_config'] = null;
				$response['list_data']    = null;
				break;
		}

		return $response;
	}

	/**
	 * Heuristic fallback classification when AI JSON is invalid.
	 *
	 * Analyzes the columns and data to determine the best output type.
	 *
	 * @param array $data    Raw result rows.
	 * @param array $columns Column names.
	 * @return array{type: string, config: array}
	 */
	public static function classify_result( array $data, array $columns ): array {
		$type         = 'answer';
		$column_names = array_map( 'strtolower', $columns );

		// Count numeric columns and find a label column.
		$numeric_cols = 0;
		$label_col    = null;

		foreach ( $columns as $col ) {
			if ( self::is_numeric_column( $col, $data ) ) {
				$numeric_cols++;
			}
			if ( in_array( strtolower( $col ), array( 'name', 'label', 'date', 'month', 'category', 'product_name', 'customer_name' ), true ) ) {
				$label_col = $col;
			}
		}

		$row_count = count( $data );

		// Heuristic: Many rows + label + numeric col → chart.
		if ( $row_count > 2 && $label_col && $numeric_cols >= 1 ) {
			$type = 'chart';
		}
		// Heuristic: Has ID columns + more than 1 row → list.
		elseif ( self::has_id_columns( $columns ) && $row_count > 1 ) {
			$type = 'list';
		}
		// Heuristic: Single row with few numeric values → answer.
		elseif ( 1 === $row_count && $numeric_cols <= 2 ) {
			$type = 'answer';
		}
		// Heuristic: Many rows with no clear label → list.
		elseif ( $row_count > 5 ) {
			$type = 'list';
		}

		return array(
			'type'   => $type,
			'config' => self::build_fallback_config( $type, $data, $columns ),
		);
	}

	/**
	 * Check if a column appears to be numeric based on sample data.
	 *
	 * @param string $col  Column name.
	 * @param array  $data Sample data rows.
	 * @return bool
	 */
	private static function is_numeric_column( string $col, array $data ): bool {
		foreach ( $data as $row ) {
			if ( isset( $row[ $col ] ) && is_numeric( $row[ $col ] ) ) {
				return true;
			}
		}
		return false;
	}

	/**
	 * Check if columns contain ID-type columns appropriate for link generation.
	 *
	 * @param array $columns Column names.
	 * @return bool
	 */
	private static function has_id_columns( array $columns ): bool {
		$id_patterns = array( 'order_id', 'product_id', 'user_id', 'customer_id', 'coupon_id', 'parent_order_id' );
		foreach ( $columns as $col ) {
			if ( in_array( $col, $id_patterns, true ) ) {
				return true;
			}
		}
		return false;
	}

	/**
	 * Build a fallback config for a given type when AI data is unavailable.
	 *
	 * @param string $type    The output type.
	 * @param array  $data    Raw result rows.
	 * @param array  $columns Column names.
	 * @return array Config data.
	 */
	private static function build_fallback_config( string $type, array $data, array $columns ): array {
		$config = array();

		switch ( $type ) {
			case 'chart':
				$config['chart_config'] = array(
					'chart_type' => 'bar',
					'title'      => __( 'Results', 'siphon-store-analytics-for-woocommerce' ),
					'labels'     => array(),
					'datasets'   => array(),
				);
				break;

			case 'list':
				$link_columns = array();
				foreach ( $columns as $col ) {
					if ( 'order_id' === $col ) {
						$link_columns[ $col ] = 'order';
					} elseif ( 'product_id' === $col ) {
						$link_columns[ $col ] = 'product';
					} elseif ( 'user_id' === $col || 'customer_id' === $col ) {
						$link_columns[ $col ] = 'user';
					} elseif ( 'coupon_id' === $col ) {
						$link_columns[ $col ] = 'coupon';
					}
				}
				$config['list_config'] = array(
					'title_column'    => $columns[0] ?? '',
					'display_columns' => $columns,
					'link_columns'    => $link_columns,
				);
				break;

			case 'answer':
			default:
				$config['answer_text'] = '';
				break;
		}

		return $config;
	}

	/**
	 * Sanitize the presentation config used to render an insight.
	 *
	 * The config arrives either from a stored history entry or from the JSON
	 * envelope the dashboard posts, and it is echoed back in the AJAX response,
	 * so nothing in it is trusted: only scalars are kept, strings are stripped
	 * of markup, and unknown nested types are dropped.
	 *
	 * @param array $insight_data Presentation config (title, answer_text, chart_config, list_config).
	 * @return array Sanitized presentation config.
	 */
	private static function sanitize_insight_data( array $insight_data ): array {
		return array(
			'title'        => is_scalar( $insight_data['title'] ?? null )
				? sanitize_text_field( (string) $insight_data['title'] )
				: '',
			// The answer is prose, so its line breaks are meaningful and are kept.
			'answer_text'  => is_scalar( $insight_data['answer_text'] ?? null )
				? sanitize_textarea_field( (string) $insight_data['answer_text'] )
				: '',
			'chart_config' => is_array( $insight_data['chart_config'] ?? null )
				? self::sanitize_config_value( $insight_data['chart_config'] )
				: null,
			'list_config'  => is_array( $insight_data['list_config'] ?? null )
				? self::sanitize_config_value( $insight_data['list_config'] )
				: null,
		);
	}

	/**
	 * Recursively sanitize a decoded JSON config tree.
	 *
	 * json_decode() does not sanitize anything, so a posted chart/list config can
	 * hold markup, nested arrays or objects. Only scalars and arrays of scalars
	 * survive; strings are passed through sanitize_text_field().
	 *
	 * @param mixed $value Config value.
	 * @param int   $depth Current recursion depth.
	 * @return mixed Sanitized value, or null when the value cannot be rendered.
	 */
	private static function sanitize_config_value( $value, int $depth = 0 ) {
		if ( is_array( $value ) ) {
			// Guard against a deeply nested payload.
			if ( $depth >= 10 ) {
				return null;
			}

			$clean = array();

			foreach ( $value as $key => $item ) {
				$item = self::sanitize_config_value( $item, $depth + 1 );

				if ( null !== $item ) {
					$clean[ $key ] = $item;
				}
			}

			return $clean;
		}

		if ( is_string( $value ) ) {
			return sanitize_text_field( $value );
		}

		// Numbers and booleans are chart settings (legends, stacking, axis
		// limits); objects and resources cannot be produced by json_decode().
		return is_int( $value ) || is_float( $value ) || is_bool( $value ) ? $value : null;
	}

	/**
	 * Re-execute a stored SQL query using the original insight config.
	 * No AI call — just re-runs the SQL and re-renders with the same formatting.
	 *
	 * When called with a single array argument, it extracts sql/type/config from it.
	 * When called with individual string/array args, it uses those directly.
	 *
	 * @param mixed  $sql_or_stored Either a string (SQL) or an array (full stored result).
	 * @param string $type          The result type (chart, list, answer).
	 * @param array  $insight_data  Stored insight config (chart_config, list_config, answer_text, etc.).
	 * @return array The complete insight response.
	 */
	public static function re_execute_sql( $sql_or_stored, string $type = 'answer', array $insight_data = array() ): array {
		// Support being called with a single array (full stored result).
		if ( is_array( $sql_or_stored ) ) {
			$stored_result = $sql_or_stored;
			$sql           = is_scalar( $stored_result['sql'] ?? null ) ? (string) $stored_result['sql'] : '';
			$type          = is_string( $stored_result['type'] ?? null ) ? $stored_result['type'] : 'answer';
			$insight_data  = array(
				'chart_config' => is_array( $stored_result['chart_config'] ?? null ) ? $stored_result['chart_config'] : null,
				'list_config'  => is_array( $stored_result['list_config'] ?? null ) ? $stored_result['list_config'] : null,
				'answer_text'  => is_scalar( $stored_result['answer_text'] ?? null ) ? (string) $stored_result['answer_text'] : null,
				'title'        => is_scalar( $stored_result['title'] ?? null ) ? (string) $stored_result['title'] : '',
			);
		} else {
			// Callers pass a string, but the parameter is mixed: anything else
			// must not reach validate( string $sql ).
			$sql = is_scalar( $sql_or_stored ) ? (string) $sql_or_stored : '';
		}

		// Both branches carry presentation config from an untrusted source (the
		// dashboard's JSON payload or a stored result), so it is sanitized before
		// it reaches the renderers or is echoed back in render_config.
		$insight_data = self::sanitize_insight_data( $insight_data );

		$type = in_array( $type, array( 'chart', 'list', 'answer' ), true ) ? $type : 'answer';

		// Validate SQL.
		$validation = SILC_WIA_SQL_Validator::validate( $sql );
		if ( ! $validation['valid'] ) {
			return array(
				'success' => false,
				'error'   => $validation['error'],
				'type'    => 'error',
				'sql'     => $sql,
			);
		}

		// Execute SQL.
		$execution = SILC_WIA_SQL_Validator::execute( $validation['sql'] );
		if ( ! $execution['success'] ) {
			return array(
				'success' => false,
				'error'   => self::format_query_error( $execution['error'] ),
				'type' => 'error',
				'sql'  => $validation['sql'],
			);
		}

		$data       = $execution['data'] ?? array();
		$columns    = ! empty( $data ) ? array_keys( $data[0] ) : array();
		$sql_time   = $execution['time_ms'] ?? 0;
		$rows_count = $execution['rows'] ?? count( $data );

		// If empty data, return empty response.
		if ( empty( $data ) ) {
			return array(
				'success'       => true,
				'type'          => $type,
				'sql'           => $validation['sql'],
				'sql_time_ms'   => $sql_time,
				'rows_returned' => 0,
				'empty'         => true,
				'empty_message' => __( 'No results found.', 'siphon-store-analytics-for-woocommerce' ),
				'columns'       => array(),
				'chart_config'  => null,
				'list_data'     => null,
				'list_config'   => null,
				'answer_text'   => null,
				'answer_value'  => null,
				'answer_label'  => null,
			);
		}

		// Render using stored config.
		$response = self::render_by_type( $data, $insight_data, $type, '' );

		$response['sql']           = $validation['sql'];
		$response['sql_time_ms']   = $sql_time;
		$response['rows_returned'] = $rows_count;
		$response['columns']       = $columns;
		$response['question']      = '';

		// Send the presentation config back with the result so a further
		// refresh re-renders identically (the rendered config carries data and
		// is not reusable as input).
		$response['render_config'] = array(
			'type'         => $type,
			'title'        => $insight_data['title'] ?? '',
			'chart_config' => $insight_data['chart_config'] ?? null,
			'list_config'  => $insight_data['list_config'] ?? null,
			'answer_text'  => $insight_data['answer_text'] ?? null,
		);

		return $response;
	}
}
